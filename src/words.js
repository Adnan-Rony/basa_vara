function below1000(n) {
  const h = Math.floor(n / 100);
  const r = n % 100;
  const parts = [];
  if (h) parts.push(UNDER_100[h] + 'শ');
  if (r) parts.push(UNDER_100[r]);
  return parts.join(' ');
}

export function numberToBanglaWords(num) {
  let n = Math.floor(Math.abs(Number(num) || 0));
  if (n === 0) return UNDER_100[0];
  const units = [
    [10000000, 'কোটি'],
    [100000, 'লাখ'],
    [1000, 'হাজার'],
  ];
  const parts = [];
  for (const [size, name] of units) {
    const q = Math.floor(n / size);
    if (q) {
      // কোটির উপরে (১০০ কোটি+) হলে আবার কোটির নিচের অংশ আলাদা করে পড়া হয়
      parts.push((size === 10000000 ? numberToBanglaWords(q) : UNDER_100[q]) + ' ' + name);
      n %= size;
    }
  }
  if (n) parts.push(below1000(n));
  return parts.join(' ');
}

export const takaInWords = (n) => numberToBanglaWords(n) + ' টাকা মাত্র';
